def main():
    files = sorted(set(glob.glob("*.py")))
    changed = []
    for f in files:
        try:
            src = open(f, "r", encoding="utf-8", newline="").read()
        except (UnicodeDecodeError, OSError):
            continue
        new = src
        for a, b in REPL:
            new = new.replace(a, b)
        if new != src:
            open(f, "w", encoding="utf-8", newline="").write(new)
            changed.append(f)
    print("changed:", len(changed))
    for f in changed:
        print("  ", f)


if __name__ == "__main__":
    main()
