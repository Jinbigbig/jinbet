def cn(name):
    """7M 港澳台译名 → 大陆常用简称；未收录原样返回（幂等）。"""
    if not name:
        return name
    return HK_TO_CN.get(str(name).strip(), name)


def _has_cjk(s):
    return any('\u4e00' <= ch <= '\u9fff' for ch in str(s or ''))


def cn_teams(teams):
    """就地归一 teams 里每项的所有名称字段。

    7M 的行 `name` 是繁体港译、`name_zh` 是简体港译（飞燕诺/阿积士），而渲染层
    原先优先读 name_zh，只改 name 依然会漏出去。规则：
      - name 是中文（7M 行）→ 以 name 为权威，归一后回写 name/name_zh/zh；
      - name 非中文（腾讯/Fox 的英文原名）→ 归一中文字段 name_zh/zh。
    """
    for t in teams or []:
        if not isinstance(t, dict):
            continue
        name = t.get('name')
        if name and _has_cjk(name):
            v = cn(name)
            t['name'] = v
            for k in ('name_zh', 'zh'):
                if t.get(k):
                    t[k] = v
        else:
            for k in ('name_zh', 'zh'):
                if t.get(k):
                    t[k] = cn(t[k])
    return teams


