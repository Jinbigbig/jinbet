def _trad2simp_chars(s):
    out = []
    for ch in s:
        out.append(_TRAD2SIMP.get(ch, ch))
    return ''.join(out)


# ALIAS 反查表：7M 繁体名 -> 我的简体名（把 港译/异译 还原为报告统一用名）
ALIAS_REV = {}
for _k, _v in ALIAS.items():
    ALIAS_REV.setdefault(_v, _k)


def to_simp(s):
    """7M 繁体名 -> 报告简体显示名。
    1) ALIAS_REV 精确命中（还原大陆译名，如 拿玻里→那不勒斯）；
    2) 否则按繁简字表逐字转换（廣島三箭→广岛三箭）。"""
    if not s:
        return s
    if s in ALIAS_REV:
        return ALIAS_REV[s]
    return _trad2simp_chars(s)


def build_index(league_data):
    """league_data: 来自 league_data.json 的 {lg: parsed}。返回 {lg: {name: row}}。"""
    idx = {}
    for lg, parsed in league_data.items():
        m = {}
        for t in parsed.get('teams', []):
            m[t['name']] = t
        idx[lg] = m
    return idx


def match_team(my_name, lg, index):
    """返回该队在 lg 积分榜中的 row dict；匹配不到返回 None。"""
    rows = index.get(lg)
    if not rows:
        return None
    # 1) 简->繁精确
    tn = _trad(my_name)
    if tn in rows:
        return rows[tn]
    # 2) 别名
    alias = ALIAS.get(my_name)
    if alias and alias in rows:
        return rows[alias]
    # 3) 子串（双向）
    for nm, row in rows.items():
        if tn and (tn in nm or nm in tn):
            return row
    return None


def match_team_strict(my_name, lg, index):
    """严格匹配（仅 简->繁精确 或 ALIAS 命中），不启用子串回退。
    用于反填「联赛排名」：宁可留空（显示「—」），也不因模糊匹配写错名次。"""
    rows = index.get(lg)
    if not rows:
        return None
    tn = _trad(my_name)
    if tn in rows:
        return rows[tn]
    alias = ALIAS.get(my_name)
    if alias and alias in rows:
        return rows[alias]
    return None


